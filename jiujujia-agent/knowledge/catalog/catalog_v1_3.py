def validate() -> list[str]:
    errs = []
    seen = set()
    for i, it in enumerate(ITEMS):
        if len(it) != 13:
            errs.append(f"第 {i} 筆欄位數不是 13")
            continue
        scene, _, _, sku, name, _, price, src, _, _, _, status, url = it
        if scene not in SCENES:
            errs.append(f"{name}：場域 {scene} 不存在")
        if (scene, sku, name) in seen:
            errs.append(f"{name}：同場域重複")
        seen.add((scene, sku, name))
        if src not in PRICE_SOURCES:
            errs.append(f"{name}：價格來源 {src} 不在 {PRICE_SOURCES}")
        if price is not None and (not isinstance(price, int) or price <= 0):
            errs.append(f"{name}：售價格式錯誤")
        if (price is None) != (src == "未查得"):
            errs.append(f"{name}：售價與價格來源不一致")
        if src == "官網" and not url.startswith(BASE):
            errs.append(f"{name}：標官網價卻不是全國電子官網網址")
        if src in ("市售", "原廠建議") and not url.startswith("https://"):
            errs.append(f"{name}：市售或原廠建議價要附來源網址")
        if src == "官網" and not sku:
            errs.append(f"{name}：官網商品要有貨號")
        if not status:
            errs.append(f"{name}：缺狀態")
    for g in GAPS:
        if g[0] not in SCENES:
            errs.append(f"缺口 {g[1]}：場域不存在")
    return errs


